    const bad = {version: 1, created_at: Date.now(), accepted: true, schema_version: '1.0', request: {product: {shape: 'rectangle', unit: 'mm', length: 100, width: 60, height: 20}}, quote_dimensions: {shape: 'rectangle', length_cm: 1, width_cm: 1, height_cm: 2}, mold_type: null};
