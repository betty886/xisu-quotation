      await expect(p.locator('#design-accept')).not.toBeChecked();
      await expect(p.locator('#design-status')).toContainText('重新计算');
      await p.locator('#product-length').fill('100');
      await p.locator('#product-unit').selectOption('cm');
      await expect(p.locator('#product-length')).toHaveValue('10');
      await expect(p.locator('#product-height')).toHaveValue('2');
      await p.locator('#design-advanced').evaluate(element => {element.open = true;});
      await p.locator('#design-mold-type').selectOption('male');
      await p.locator('#shrinkage-percent').fill('0.5');
      const designRequest = p.waitForRequest(request => request.url().endsWith('/api/design') && request.method() === 'POST');
      await p.locator('#design-calculate').click();
      assert.equal((await designRequest).postDataJSON().tooling.shrinkage_fraction, 0.005);
      await expect(p.locator('#design-mold')).toContainText('工程参考');
      await p.locator('#design-accept').check();
      await p.locator('#design-transfer').click();
      await expect(p.locator('#design-source')).toBeVisible();
      await expect(p.locator('#design-source')).toContainText('按产品推算，待样品确认');
      await expect(p.locator('#length')).toHaveValue('12.01');
      await expect(p.locator('#width')).toHaveValue('8.01');
      await expect(p.locator('#height')).toHaveValue('2');
      await expect(p.locator('#mold-male')).toBeChecked();
      await expect(p.locator('input[name="dimensionUnit"][value="cm"]')).toBeChecked();
      await p.locator('#variant').selectOption({label: 'PET透明'});
      await p.locator('#quantity').fill('10000');
      const quoteRequest = p.waitForRequest(request => request.url().endsWith('/api/quote') && request.method() === 'POST');
      await p.locator('#calculate').click();
      const quote = (await quoteRequest).postDataJSON();
      assert.equal(quote.length, '12.01');
      assert.equal(quote.width, '8.01');
      await expect(p.locator('#copy-quote')).toBeEnabled();
      let releaseVerification;
      const verificationGate = new Promise(resolve => {releaseVerification = resolve;});
      let observeVerification;
      const verificationStarted = new Promise(resolve => {observeVerification = resolve;});
      const holdVerification = async route => {observeVerification(); await verificationGate; await route.continue();};
      await p.route('**/api/design', holdVerification);
      await p.reload();
      await verificationStarted;
      await expect(p.locator('#quantity')).toHaveValue('10000');
      await p.locator('#quantity').fill('20000');
      releaseVerification();
      await expect(p.locator('#design-source')).toBeVisible();
      await expect(p.locator('#quantity')).toHaveValue('20000');
      assert.equal(await p.evaluate(() => JSON.parse(sessionStorage.getItem('xisu.quote.draft.v1')).design_source.schema_version), '1.0');
      await p.unroute('**/api/design', holdVerification);
      await p.locator('#quantity').fill('10000');
      await p.locator('label').filter({has: p.locator('#mold-female')}).click();
      await expect(p.locator('#design-source')).toBeHidden();
      await p.locator('#length').fill('30');
      await p.locator('#design-entry').click();
      await p.locator('#product-shape').selectOption('circle');
      await p.locator('#product-length').fill('100');
      await p.locator('#product-height').fill('20');
      await p.locator('#design-advanced').evaluate(element => {element.open = true;});
      await p.locator('#design-mold-type').selectOption('male');
      await p.locator('#shrinkage-mode').selectOption('axes');
      await p.locator('#shrinkage-length').fill('0.5');
      await p.locator('#shrinkage-width').fill('1');
      await p.locator('#shrinkage-height').fill('0.2');
      await p.locator('#design-calculate').click();
      await expect(p.locator('#design-mold')).toContainText('长向 102.513 × 宽向 103.030 mm');
      await p.locator('#design-accept').check();
      await p.locator('#design-transfer').click();
      await expect(p.locator('#design-conflict')).toBeVisible();
      await expect(p.locator('#length')).toHaveValue('30');
      await expect(p.locator('#quantity')).toHaveValue('10000');
